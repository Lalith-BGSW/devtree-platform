"""
AI-PROPOSED DTS: the AI drafts a completed / corrected USB device tree, and Python decides what is trustworthy.

Why this is not "just let the AI write it": earlier AI drafts in this project looked proper and were not - stale
2 mA drive strengths, a fabricated `microchip,usb2514` hub with `reg = <0x2d>`, USB20 pins labelled for USB30,
duplicate pin definitions. Nothing in such a draft shows which lines are the wrong ones. So every draft goes
through a generate -> verify -> repair loop with deterministic checks:

  1. The AI is given the tool's VERIFIED_DTS (generated straight from the workbook), EVIDENCE for the pins the tool
     refused to generate, and FACTS the engineer typed (decisions, datasheet values). Those are its only sources.
  2. The existing verifier (tool/verify_dts.py) checks the draft against the Excel. Wrong values, wrong pins,
     shared-pin use, duplicate definitions come back as exact findings and the AI must fix them (max 2 repair rounds).
  3. Verified lines the AI altered or dropped are found by comparing with VERIFIED_DTS and sent back too.
  4. dtc must compile it (syntax / labels), when dtc is installed.
  5. A source guard marks every ADDED line whose specifics (I2C address, "vendor,model" compatible, output level,
     GPIO flag, GPIO number, a base-tree label) are in none of: the verified output, the evidence, the FACTS.
     Those lines are annotated UNVERIFIED and listed - never silently accepted.

  6. HYBRID FINAL: every flagged line is demoted to a `//` comment (a whole node if the flagged line opens one), and the
     merged result is verified and compiled again. So the final file contains only (a) Python-generated nodes and
     (b) AI additions that passed every check - everything else is visible as a comment, with the reason.

AI FIRST, THEN PYTHON: `extract_facts()` lets the AI read documents the engineer supplies (datasheet notes, schematic
text) and extract facts, each with a verbatim quote. Python rejects any fact whose quote does not literally occur in the
document, or whose specifics (address, compatible, level) are not inside that quote. Accepted facts feed the generation.

The result is the hybrid final plus a diff against the Python-only output. The Python-only output is never modified.
"""

