SYSTEM_PROMPT = """You complete a Linux device tree for the USB subsystem of an automotive SoC.

You are given:
- VERIFIED_DTS: pinctrl nodes (and possibly consumer nodes) generated by a deterministic tool straight from the hardware workbook.
- EVIDENCE: for pins the tool refused to generate (shared, boot-strap, other pin controller): what the workbook says.
- FACTS: numbered statements from the responsible engineer (decisions, schematic or datasheet values). They are the ONLY source for anything the workbook does not state.
- PATTERN: controller | regulator | unconfirmed.
- Optionally a DRAFT to correct, together with exact FINDINGS from an automatic checker.

Rules:
1. Copy every VERIFIED_DTS line unchanged. Never change or drop a verified value, pin, label or node.
   The only permitted edit inside a verified node: replace the line `/* NEEDS REVIEW: output pin ... */` by `output-high;` or `output-low;` when a FACT states that level for that pin.
2. You may add: consumer nodes (&usbN) that reference the verified pin labels according to PATTERN (controller: oc-gpio, vbus-out-gpio, pinctrl-names, pinctrl-0; regulator: regulator-fixed + vbus_dwc3-supply); and anything a FACT explicitly provides (a hub node, an I2C child node, a level...).
   If PATTERN is unconfirmed and no FACT chooses one, add NO consumer node.
3. Anything else you would need that is in neither the workbook nor the FACTS - a compatible string, an I2C address, an output level, a controller label, a regulator name, a property you cannot justify - must NOT be invented. Write `/* NEEDS REVIEW: <what is missing> */` instead.
4. After each added property that comes from a FACT write `/* source: FACT <n> */`.
5. Reply with ONE fenced ```dts block containing the complete DTS, and nothing else.
6. When FINDINGS are given, fix exactly those problems in the full DTS and reply again with the complete corrected block.
7. If a FACT cannot be fully applied because something is missing (for a hub or I2C device: the I2C controller label, the pin or net), do not guess and do NOT create a node for it. Write one comment line next to the related VERIFIED node that names the real fact number and says what is missing.
8. Never add a node, label, compatible string, regulator or property that is not in VERIFIED_DTS, a FACT or the EVIDENCE. An empty node, or a node containing only a comment, is never acceptable."""

_FENCE = re.compile(r"```(?:dts|dtsi|devicetree)?[ \t]*\n(.*?)```", re.S)
_SPECIFICS = (
    ("I2C address / hex value", re.compile(r"0x[0-9a-fA-F]+")),
    ("compatible-style string", re.compile(r'"[a-z][a-z0-9_-]*,[a-z0-9][\w.\-]*"')),
    ("output level", re.compile(r"\boutput-(?:high|low)\b")),
    ("GPIO flag", re.compile(r"\bGPIO_ACTIVE_(?:HIGH|LOW)\b")),
)
_BASE_LABELS_ALWAYS_OK = {"tlmm"}


def extract_dts(raw: str) -> str:
    raw = raw or ""
    m = _FENCE.search(raw)
    text = (m.group(1) if m else raw).strip("\n")
    return text + "\n" if text.strip() else ""


def _nl(line: str) -> str:
    return re.sub(r"\s+", " ", line).strip()


def _code(line: str) -> str:
    return re.sub(r"/\*.*?\*/", "", line)


def _is_level_placeholder(line: str) -> bool:
    return "NEEDS REVIEW: output pin" in line


def _sources(tool_out: str, evidence: list, facts: str) -> dict:
    blob = _nl(tool_out + "\n" + facts + "\n" + json.dumps(evidence)).lower()
    return {"norm": blob, "gpios": set(re.findall(r"gpio[_\s\-]?(\d+)", blob))}


def _supported(kind: str, token: str, src: dict) -> bool:
    """Whole-token match: 'gpio9' must not be accepted just because 'gpio92' occurs, '0x2d' not because of '0x2d0'."""
    if kind == "GPIO number":
        return token[4:] in src["gpios"]
    t = token.strip('"').lower()
    return re.search(r"(?<![a-z0-9_])" + re.escape(t) + r"(?![a-z0-9_])", src["norm"]) is not None


def source_guard(proposal: str, tool_out: str, evidence: list, facts: str) -> list[tuple[int, str, str]]:
    """[(line_no, kind, token)] for every ADDED line carrying a specific that is in none of the allowed sources."""
    src = _sources(tool_out, evidence, facts)
    known = {_nl(l) for l in tool_out.splitlines() if l.strip()}
    tool_labels = set(re.findall(r"&([A-Za-z_]\w*)", tool_out))
    # An output level is backed only for the PIN a fact names: "gpio82 boots output-low" must not license a level on gpio113.
    fact_levels = set()
    for fact in fact_lines(facts):
        lvl = _fact_level(fact)
        pins = set(re.findall(r"gpio[_\s-]?(\d+)", _fact_text_only(fact), re.I))
        if lvl and len(pins) == 1:
            fact_levels.add((f"gpio{next(iter(pins))}", lvl))
    flagged: list[tuple[int, str, str]] = []
    cur_pin = None
    depth, top, stack = 0, None, []
    for i, line in enumerate(proposal.splitlines(), 1):
        if re.match(r"^\s*[A-Za-z_]\w*\s*:\s*[\w@,.\-]+\s*\{", line):
            cur_pin = None
        pm = re.search(r'pins\s*=\s*"(gpio\d+)"', line)
        if pm:
            cur_pin = pm.group(1)
        code = _code(line)
        # structure tracking: which top-level block are we in, and which line opened the current node
        if depth == 0:
            mt = re.match(r"^(&[A-Za-z_]\w*|/|[A-Za-z_]\w*\s*:\s*[\w@,.\-]+)\s*\{", code)
            top = mt.group(1).replace(" ", "") if mt else top
        opens, closes = code.count("{"), code.count("}")
        if opens > closes:
            stack.append(i)
        for _ in range(max(0, closes - opens)):
            if stack:
                stack.pop()
        depth = max(0, depth + opens - closes)
        if 'compatible = "regulator-fixed"' in code and top == "&tlmm" and stack:
            flagged.append((stack[-1], "regulator inside &tlmm", "regulator-fixed"))      # a regulator is not a pin-controller child
        if not code.strip() or _nl(line) in known:
            continue
        hm = re.match(r"^\s*(?:([A-Za-z_]\w*)\s*:\s*)?([A-Za-z_][\w,.\-]*)(?:@[\w,]+)?\s*\{\s*$", code)
        if hm:                                           # a node header the AI ADDED: its name must come from a source
            for tok in [t for t in (hm.group(2), hm.group(1)) if t]:
                if not re.search(r"(?<![a-z0-9_])" + re.escape(tok.lower()) + r"(?![a-z0-9_])", src["norm"]):
                    flagged.append((i, "new node", tok))
                    break
        found = []
        for kind, rx in _SPECIFICS:
            found += [(kind, m.group(0)) for m in rx.finditer(code)]
        found += [("GPIO number", f"gpio{m.group(1)}") for m in re.finditer(r"&tlmm\s+(\d+)", code)]
        for m in re.finditer(r"&([A-Za-z_]\w*)", code):
            lab = m.group(1)
            if lab not in _BASE_LABELS_ALWAYS_OK and lab not in tool_labels:
                found.append(("base-tree label", lab))
        for kind, tok in found:
            ok = ((cur_pin, tok.lower()) in fact_levels) if (kind == "output level" and cur_pin) else _supported(kind, tok, src)
            if not ok:
                flagged.append((i, kind, tok if kind != "output level" or not cur_pin else f"{tok} (on {cur_pin})"))
    return flagged


def annotate(proposal: str, flagged: list[tuple[int, str, str]]) -> str:
    by_line: dict[int, list[str]] = {}
    for ln, kind, tok in flagged:
        by_line.setdefault(ln, []).append(f"{kind} '{tok}'")
    out = []
    for i, line in enumerate(proposal.splitlines(), 1):
        if i in by_line:
            line += "  /* UNVERIFIED: " + "; ".join(by_line[i]) + " - not in the verified output, the evidence or your facts */"
        out.append(line)
    return "\n".join(out) + "\n"


def demote(text: str, flagged: list[tuple[int, str, str]]) -> str:
    """Turn every flagged line into a `//` comment. A flagged line that opens a node takes the whole balanced node with
    it, so braces stay balanced. Nothing is deleted: the original text stays visible, with the reason."""
    lines = text.splitlines()
    why: dict[int, str] = {}
    for ln, kind, tok in flagged:
        i = ln - 1
        why.setdefault(i, f"{kind} {tok}")
        code = _code(lines[i])
        if code.count("{") > code.count("}"):
            depth = 0
            for j in range(i, len(lines)):
                c = _code(lines[j])
                depth += c.count("{") - c.count("}")
                why.setdefault(j, f"{kind} {tok} (part of the node it opens)")
                if depth <= 0:
                    break
    level_lines = {ln - 1 for ln, kind, _t in flagged if kind == "output level"}
    out = []
    for i, line in enumerate(lines):
        if i in why:
            out.append(f"// UNVERIFIED [{why[i]} is not in the workbook, the verified output or your facts]: {line.strip()}")
            if i in level_lines:
                out.append(f"{re.match(r'\s*', line).group(0)}/* NEEDS REVIEW: output pin - add output-high or output-low per "
                           f"hardware design (level is not derivable from Excel) */")
        else:
            out.append(line)
    return "\n".join(out) + "\n"


FACTS_PROMPT = """You extract engineering FACTS from ONE document, for the device tree of an automotive USB subsystem.

Extract only what the document literally states about: USB hub or controller part and its compatible string, I2C address, reset/enable/over-current polarity or boot level, VBUS regulator voltage, which connector or net carries which signal, which controller instance maps to which label.
For every fact give a QUOTE copied VERBATIM from the document (at most 200 characters). Do not infer, combine or guess. If the document states nothing relevant, return an empty list.
Reply with a single JSON object and nothing else:
{"facts": [{"fact": "<one plain sentence>", "quote": "<verbatim text from the document>"}]}   (at most 12 facts)"""


def read_document(path: str) -> str:
    """Read a text/markdown file the way Windows tools write it: UTF-8, UTF-8 with BOM, or UTF-16 (what PowerShell's
    `>` produces). Reading UTF-16 as UTF-8 yields NUL-filled garbage in which no quote could ever match."""
    raw = open(path, "rb").read()
    if raw[:2] in (b"\xff\xfe", b"\xfe\xff") or (len(raw) > 3 and raw.count(b"\x00") > len(raw) // 4):
        return raw.decode("utf-16", errors="replace").lstrip("\ufeff")
    return raw.decode("utf-8-sig", errors="replace")


def extract_facts(docs: dict) -> dict:
    """AI reads documents, Python verifies. {"facts": [str], "rejected": int, "unavailable": str|None, "error": str|None,
    "usage": {...}}. A fact is kept only if its quote occurs in the document and every specific in the fact is in the quote."""
    from app.usb_ai_advisor import _parse
    client = llm_client.get_client(FEATURE)
    if client is None:
        why = ("no LLM is configured" if not llm_client.is_configured() else f"the '{FEATURE}' feature is not enabled")
        return {"facts": [], "rejected": 0, "unavailable": why, "error": None, "usage": {}}
    before = dict(llm_client.usage_totals)
    facts, rejected, error, per_doc = [], 0, None, []
    for name, text in docs.items():
        body = text[:30000]
        st = {"doc": name, "chars": len(text), "returned": 0, "accepted": 0, "rejected": 0, "note": None}
        per_doc.append(st)
        if not text.strip():
            st["note"] = "the file is empty - nothing to read"
            continue
        try:
            resp = client.chat.completions.create(
                messages=[{"role": "system", "content": FACTS_PROMPT},
                          {"role": "user", "content": f"DOCUMENT {name}:\n{body}"}], temperature=0.0, max_tokens=1500)
        except llm_client.LLMError as e:
            error = str(e)
            break
        obj = _parse(resp.choices[0].message.content)
        if obj is None:
            st["note"] = "the AI reply was not usable JSON, so nothing could be read from this document"
            continue
        items = obj.get("facts") if isinstance(obj.get("facts"), list) else []
        st["returned"] = len(items)
        if not items:
            st["note"] = "the AI found no relevant fact in this document"
        doc_norm = _nl(body).lower()
        for item in items[:12]:
            fact = _nl(str((item or {}).get("fact") or ""))
            quote = _nl(str((item or {}).get("quote") or ""))
            if not fact or not quote or quote.lower() not in doc_norm:
                rejected += 1                                   # the quote is not in the document: the fact is not accepted
                st["rejected"] += 1
                continue
            qsrc = {"norm": quote.lower(), "gpios": set()}
            if any(not _supported(k, m.group(0), qsrc) for k, rx in _SPECIFICS for m in rx.finditer(fact)):
                rejected += 1                                   # the AI put a specific in the fact that its quote does not contain
                st["rejected"] += 1
                continue
            facts.append(f'{fact} (from {name}: "{quote[:200]}")')
            st["accepted"] += 1
    return {"facts": facts, "rejected": rejected, "unavailable": None, "error": error, "docs": per_doc,
            "usage": {k: llm_client.usage_totals[k] - before[k] for k in before}}


def render_facts_report(fx: dict) -> list[str]:
    head = ["\n## Facts extracted from your documents (AI read them, Python verified each quote)\n"]
    if fx.get("unavailable"):
        return head + [f"Document reading was requested but is unavailable: {fx['unavailable']}."]
    lines = head + [f"{len(fx['facts'])} fact(s) accepted, {fx['rejected']} rejected (the quote was not literally in the document, "
                    f"or the fact contained a specific its quote did not)."]
    for d in fx.get("docs", []):
        lines.append(f"- `{d['doc']}`: {d['chars']} characters read, the AI returned {d['returned']} fact(s) -> "
                     f"{d['accepted']} accepted, {d['rejected']} rejected" + (f" ({d['note']})" if d["note"] else ""))
    lines += [""] + [f"{n}. {f}" for n, f in enumerate(fx["facts"], 1)]
    if fx.get("error"):
        lines.append(f"\nReading stopped early: {fx['error']}")
    return lines


_LEVEL_RX = (re.compile(r"\boutput[-_ ]?(high|low)\b", re.I),
             re.compile(r"\bboots?\s+(?:at\s+|to\s+|as\s+|in\s+)?(?:a\s+)?(high|low)\b", re.I),
             re.compile(r"\b(high|low)\s+at\s+boot\b", re.I))


def _fact_text_only(fact: str) -> str:
    return re.split(r"\s+\(from [^\n()]*?:\s", fact, maxsplit=1)[0].strip()      # cut at the source note; the quote inside it may hold parentheses, e.g. "(GPIO_11)"


def _fact_level(fact: str):
    f = _fact_text_only(fact)
    for rx in _LEVEL_RX:
        m = rx.search(f)
        if m:
            return "output-" + m.group(1).lower()
    return None


def fact_lines(facts: str) -> list[str]:
    return [l.strip() for l in (facts or "").splitlines() if l.strip()]


def apply_level_facts(text: str, facts: str):
    """PYTHON FIRST. A fact that names ONE pin and states its boot level ("gpio82 boots output-low per the schematic") is a
    fixed, mechanical edit - no reason to ask a language model to do it (one did not, in a real run). The generated
    `/* NEEDS REVIEW: output pin ... */` placeholder (or a flagged inferred level) of that pin's node becomes the stated
    level, tagged with its source. Returns (new_text, [(n, pin, level)], [(n, why_not)]). Wording that is not unambiguous
    ("reset is active low") is never read as a level."""
    lines = text.splitlines()
    applied, unapplied = [], []
    for n, fact in enumerate(fact_lines(facts), 1):
        level = _fact_level(fact)
        if not level:
            continue
        pins = sorted(set(re.findall(r"gpio[_\s-]?(\d+)", _fact_text_only(fact), re.I)))
        if len(pins) != 1:
            unapplied.append((n, "it states a level but names no pin" if not pins else "it names more than one pin"))
            continue
        pin, cur, done = f"gpio{pins[0]}", None, False
        for i, l in enumerate(lines):
            if re.match(r"^\s*[A-Za-z_]\w*\s*:\s*[\w@,.\-]+\s*\{", l):
                cur = None
            m = re.search(r'pins\s*=\s*"(gpio\d+)"', l)
            if m:
                cur = m.group(1)
            if cur == pin and ("NEEDS REVIEW: output pin" in l
                               or re.search(r"output-(?:high|low);\s*/\*\s*(?:NEEDS REVIEW: level inferred|source: Excel ResetValue)", l)):
                lines[i] = f"{re.match(r'\s*', l).group(0)}{level};  /* source: FACT {n} */"
                applied.append((n, pin, level))
                done = True
                break
        if not done:
            unapplied.append((n, f"no generated node for {pin} has a level left to set (it is not in this run, or the workbook already fixes it)"))
    return "\n".join(lines) + "\n", applied, unapplied


_FACT_SPECIFICS = re.compile(r"0x[0-9a-fA-F]+|\b[a-z][a-z0-9_-]*,[a-z0-9][\w.\-]*\b")


def fact_accounting(facts: str, applied: list, unapplied: list, final: str) -> list[dict]:
    """What happened to EACH fact the engineer gave - so none is silently ignored."""
    done = {a[0]: a for a in applied}
    why = dict(unapplied)
    active = "\n".join(l for l in final.splitlines() if not l.lstrip().startswith("//")).lower()
    out = []
    for n, fact in enumerate(fact_lines(facts), 1):
        if n in done:
            status, note = "applied by Python", f"{done[n][1]} -> {done[n][2]}"
        elif n in why:
            status, note = "NOT applied", why[n]
        else:
            specs = _FACT_SPECIFICS.findall(_fact_text_only(fact))
            hits = [t for t in specs if re.search(r"(?<![a-z0-9_])" + re.escape(t.lower()) + r"(?![a-z0-9_])", active)]
            if specs and hits:
                status, note = "used by the AI", "appears in the final file: " + ", ".join(hits)
            elif specs:
                status, note = "NOT used", ("the AI did not add anything for it. Usually something needed to place it is missing from "
                                            "your facts - for a hub or I2C device: the I2C controller label (the bus), and which "
                                            "pin or net it is on")
            else:
                status, note = "context only", "nothing in it can be checked or placed as a value"
        out.append({"n": n, "fact": _fact_text_only(fact)[:160], "status": status, "note": note})
    return out


def _top_blocks(text: str):
    out = []
    for m in re.finditer(r"^(&[A-Za-z_]\w*|[A-Za-z_]\w*\s*:\s*[\w@,.\-]+|/)\s*\{", text, re.M):
        o = text.index("{", m.start())
        try:
            c = _find_matching_brace(text, o)
        except Exception:
            continue
        end = c + 1 + (1 if text[c + 1:c + 2] == ";" else 0)
        out.append((m.group(1).strip(), text[m.start():end]))
    return out


def hybrid_combined(combined: str, python_only: str, hybrid: str):
    """The Combined View, updated: pinctrl nodes the hybrid changed are replaced IN PLACE (tagged), and anything the hybrid
    ADDED that Python did not generate goes into a separate, labelled section 4. Returns (text, number_of_changes) or
    (None, 0) when the hybrid changed nothing."""
    py = {n.label: n.raw_text.strip() for n in parse_dts_nodes(python_only)}
    hy = {n.label: n.raw_text.strip() for n in parse_dts_nodes(hybrid)}
    out, changes = combined, 0
    for lbl, raw in hy.items():
        if lbl in py and _nl(py[lbl]) != _nl(raw) and py[lbl] in out:
            out = out.replace(py[lbl], "/* HYBRID: updated from your facts / verified AI - Python generated the rest of this node */\n\t" + raw, 1)
            changes += 1
    added = []
    new_nodes = [raw for lbl, raw in hy.items() if lbl not in py]
    if new_nodes:
        added.append("&tlmm {\n" + "\n".join("\t" + r + ("" if r.endswith(";") else ";") for r in new_nodes) + "\n};")
    py_blocks = {_nl(b) for _h, b in _top_blocks(python_only)}
    for head, raw in _top_blocks(hybrid):
        if head != "&tlmm" and _nl(raw) not in py_blocks:
            added.append(raw)
    if added:
        out = out.rstrip("\n") + ("\n\n/* 4. AI-ADDED AND VERIFIED - not generated by Python. Every value below passed the checks "
                                  "and comes from the workbook, your facts or your documents. */\n\n" + "\n\n".join(added) + "\n")
        changes += len(added)
    return (out, changes) if changes else (None, 0)


_PLACEHOLDER = re.compile(r"FACT\s*<[^>]*>|<n>|<what[^>]*>|<[a-z ]*missing[a-z ]*>|<fact[^>]*>", re.I)


def strip_placeholders(text: str):
    """Remove lines that still contain an unfilled template placeholder (the model copied a pattern instead of an answer).
    Returns (text, number_removed)."""
    keep, gone = [], 0
    for line in text.splitlines():
        if _PLACEHOLDER.search(line):
            gone += 1
        else:
            keep.append(line)
    return "\n".join(keep) + "\n", gone


def pins_with_marker(text: str, marker: str) -> list[str]:
    """Pins (gpioN) whose generated node contains `marker` - so messages can name the REAL pins of this run."""
    out, cur = [], None
    for line in text.splitlines():
        if re.match(r"^\s*[A-Za-z_]\w*\s*:\s*[\w@,.\-]+\s*\{", line):
            cur = None
        m = re.search(r'pins\s*=\s*"(gpio\d+)"', line)
        if m:
            cur = m.group(1)
        if marker in line and cur and cur not in out:
            out.append(cur)
    return out


def missing_verified_lines(proposal: str, tool_out: str) -> list[str]:
    have = {_nl(l) for l in proposal.splitlines() if l.strip()}
    return [l.strip() for l in tool_out.splitlines()
            if l.strip() and not _is_level_placeholder(l) and not _code(l).strip() == "" and _nl(l) not in have]


def _fmt_findings(findings: list[str]) -> str:
    return "FINDINGS from the automatic checker (fix exactly these, keep everything else):\n" + "\n".join(
        f"- {f}" for f in findings[:25])


def _user_message(tool_out, evidence, facts, pattern, draft, applied=()) -> str:
    parts = [f"PATTERN: {pattern}", "VERIFIED_DTS:\n```dts\n" + tool_out.rstrip("\n") + "\n```"]
    if applied:
        parts.append("ALREADY APPLIED BY PYTHON (keep exactly as it is in VERIFIED_DTS): "
                     + "; ".join(f"FACT {n}: {pin} {lvl}" for n, pin, lvl in applied))
    parts.append("EVIDENCE:\n" + (json.dumps(evidence, indent=1) if evidence else "(none - nothing was flagged)"))
    fl = [l.strip() for l in (facts or "").splitlines() if l.strip()]
    parts.append("FACTS:\n" + ("\n".join(f"FACT {n}: {t}" for n, t in enumerate(fl, 1)) if fl else "(none supplied)"))
    if draft:
        parts.append("DRAFT to correct (from the engineer; keep what is right, fix what the checker finds):\n```dts\n"
                     + draft.rstrip("\n") + "\n```")
    return "\n\n".join(parts)


def propose(tool_out: str, evidence: list, facts: str, pattern: str, verify, draft: str | None = None,
            max_rounds: int = MAX_REPAIR_ROUNDS, allow_no_ai: bool = False, skip_ai: bool = False) -> dict:
    """verify(text) -> {"wrong": [(line,item,msg)], "ambiguous": [...], "unverifiable": [...], "ok": int,
    "dtc": (ok|None, message)}. Never raises: any failure becomes status/error in the returned dict."""
    client = llm_client.get_client(FEATURE)
    no_ai = None
    if client is None:
        why = ("no LLM is configured (set LLM_API_KEY and LLM_DEPLOYMENT in backend/.env)"
               if not llm_client.is_configured() else f"the '{FEATURE}' feature is not enabled in LLM_FEATURES")
        if not allow_no_ai:
            return {"status": "unavailable", "reason": why}
        no_ai = why        # Python still has something to deliver (template completion / facts): do that, say the AI was not used
    elif skip_ai:
        # The AI only completes what the workbook cannot state, from facts / documents / a draft. With none of those it has nothing
        # to add - a call would only cost tokens (and risk invented lines that the guards then have to remove).
        no_ai = ("nothing for the AI to complete - no facts, documents or draft were supplied; add one in Advanced options to engage it. "
                 "Python's output, verified, is the result")

    before = dict(llm_client.usage_totals)
    original = tool_out
    tool_out, applied, unapplied = apply_level_facts(original, facts)       # Python first: simple, unambiguous facts
    messages = [{"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": _user_message(tool_out, evidence, facts, pattern, draft, applied)}]
    rounds, text, last_check, error, ph_removed = [], "", None, None, 0

    def check(candidate: str):
        v = verify(candidate)
        findings = [f"line {ln}: {item}: {msg}" for ln, item, msg in v["wrong"]]
        findings += [f"line {ln}: {item}: AMBIGUOUS - {msg}" for ln, item, msg in v["ambiguous"]]
        if v["dtc"][0] is False:
            findings.append("dtc cannot compile it: " + v["dtc"][1])
        gone = missing_verified_lines(candidate, tool_out)
        findings += [f"you changed or dropped this VERIFIED line (restore it exactly): {l}" for l in gone[:12]]
        return v, findings, gone

    # A draft that is already supplied is checked BEFORE the AI touches it: that is the first set of findings.
    need_ai = True
    if draft:
        last_check = check(draft)
        f0 = last_check[1]
        rounds.append({"round": 0, "source": "your draft", "problems": len(f0)})
        if f0:
            messages.append({"role": "user", "content": _fmt_findings(f0)})
        else:
            text, need_ai = draft, False          # the draft already passes every check: nothing for the AI to fix

    if no_ai:
        need_ai = False
        if not text:
            text = tool_out
            last_check = check(text)
            rounds.append({"round": 0, "source": "Python only", "problems": len(last_check[1])})

    if need_ai:
        for rnd in range(1, max_rounds + 2):
            try:
                resp = client.chat.completions.create(messages=messages, temperature=0.0, max_tokens=3500)
            except llm_client.LLMError as e:
                error = str(e)
                break
            raw = resp.choices[0].message.content or ""
            text = extract_dts(raw)
            if not text:
                error = "the AI did not return any DTS"
                break
            text, gone_ph = strip_placeholders(text)
            ph_removed += gone_ph
            last_check = check(text)
            findings = last_check[1]
            rounds.append({"round": rnd, "source": "AI", "problems": len(findings), "examples": findings[:3]})
            if not findings or rnd == max_rounds + 1:
                break
            messages += [{"role": "assistant", "content": raw}, {"role": "user", "content": _fmt_findings(findings)}]

    if not text:
        return {"status": "failed", "reason": error or "no proposal was produced", "rounds": rounds}

    v, findings, gone = last_check if last_check else (verify(text), [], [])
    flagged = source_guard(text, tool_out, evidence, facts)
    annotated = annotate(text, flagged)
    final = text
    if flagged:
        final = demote(text, flagged)                     # the merged, safe file: unsupported AI lines become comments
        v, findings, gone = check(final)                  # ... and it is verified + compiled AGAIN, as it will be used
    used = {k: llm_client.usage_totals[k] - before[k] for k in before}
    # No active DTS at all (e.g. every USB GPIO sits on a pin controller this tool cannot generate for): "passed every check" would be
    # true of nothing. Say so instead.
    empty = not re.search(r"\{", re.sub(r"/\*.*?\*/|//[^\n]*", "", final, flags=re.S))
    return {
        "status": "empty" if empty and not findings and not error else ("clean" if not findings and not error else "needs_attention"),
        "text": annotated, "final_text": final, "rounds": rounds, "error": error, "usage": used,
        "ai_note": no_ai, "placeholders_removed": ph_removed, "python_only_text": original, "facts_applied": [{"n": n, "pin": pin, "level": lvl} for n, pin, lvl in applied],
        "facts_report": fact_accounting(facts, applied, unapplied, final),
        "verification": {"wrong": len(v["wrong"]), "ambiguous": len(v["ambiguous"]), "unverifiable": len(v["unverifiable"]),
                         "ok": v["ok"], "dtc": v["dtc"][1], "changed_verified_lines": len(gone)},
        "open_findings": findings,
        "unsupported": [{"line": ln, "kind": k, "token": t} for ln, k, t in flagged],
        "unverifiable_items": [f"line {ln}: {item}: {msg}" for ln, item, msg in v["unverifiable"]][:20],
        "diff": "".join(list(difflib.unified_diff(original.splitlines(True), final.splitlines(True),
                                                   "python_only_output.dtsi", "hybrid_final.dtsi", n=1))[:160]),
    }


def render_report(res: dict, proposal_path: str | None) -> list[str]:
    head = ["\n## Hybrid output - Python-verified nodes plus the AI additions that passed every check\n"]
    if res["status"] == "unavailable":
        return head + [f"An AI proposal was requested but is unavailable: {res['reason']}. Nothing else is affected."]
    if res["status"] == "failed":
        return head + [f"The AI proposal failed: {res['reason']}. The verified output above is unaffected."]
    v = res["verification"]
    banner = []
    if res.get("template_assumed"):
        tp, src = res.get("template_pattern", "regulator"), res.get("template_source", "an accepted example")
        weak = "" if res.get("template_same_soc", True) else " This is a DIFFERENT SoC than the example, so the evidence is weaker."
        if tp == "controller":
            how = ("`&usbN` blocks with `oc-gpio` and `vbus-out-gpio`, the `pinctrl-0` states, and the dwc3 child only where it was "
                   "confirmed for this SoC")
        else:
            how = ("regulator-fixed VBUS regulators, `&usbN` consumers with `vbus_dwc3-supply`, and output levels by the \"regulator off at "
                   "boot\" convention (active-low enable -> `output-high`, active-high enable -> `output-low`); every inferred level is tagged")
        banner = [f"**PATTERN ASSUMED.** No project file confirms how this project wires VBUS and over-current, and none was chosen, so the "
                  f"output follows the **{tp}** style of {src}: {how}.{weak} Choose a pattern yourself, or attach the project's own DTS, "
                  f"to remove this assumption.", ""]
    state = ("NO AUTOMATIC FINDINGS - the final file passed every automatic check; this is not \"ready to merge\": the decisions and unverifiable lines below are still open" if res["status"] == "clean"
             else "NOTHING GENERATED - there was no DTS to verify (see the lists below for why)" if res["status"] == "empty"
             else "NEEDS ATTENTION - read the lists below before using any of it")
    lines = head + banner + [
        f"**Status: {state}.** Final file written to `{proposal_path}`." if proposal_path else f"**Status: {state}.**",
        "",
        "Every active line in the final file is either generated by Python or an AI addition that passed Python's checks: values "
        "against the Excel, verified lines compared with the tool's output, a `dtc` compile when `dtc` is installed, and a source check on anything the AI added. "
        "AI lines that failed the source check are kept as `// UNVERIFIED` comments - visible, not active. The Python-only output above is unchanged.",
        "",
        "- Rounds: " + ", ".join("%s #%d: %d problem(s)" % (r["source"], r["round"], r["problems"]) for r in res["rounds"]),
        f"- Verifier on the final draft: {v['wrong']} wrong | {v['ambiguous']} ambiguous | {v['unverifiable']} unverifiable | {v['ok']} confirmed OK",
        f"- Verified lines changed or dropped by the AI: {v['changed_verified_lines']}",
        f"- {v['dtc']}",
        f"- Model usage: {res['usage']['calls']} call(s), {res['usage']['prompt_tokens']} in / {res['usage']['completion_tokens']} out tokens",
    ]
    for r in res["rounds"]:
        if r["problems"] and r.get("examples") and r is not res["rounds"][-1]:
            lines.append(f"- {r['source']} #{r['round']}: {r['problems']} problem(s) were found by Python and sent back to the AI to fix, e.g. "
                         + "; ".join(x[:140] for x in r["examples"]))
    if res.get("ai_note"):
        lines.append(f"- The AI wrote none of this output - its 'complete the DTS' step was skipped: {res['ai_note']}. Everything here is Python-generated; a fact that names one pin and a level was applied by Python. (Other AI features may still have run: see 'Where the AI was used in this run'.)")
    if res.get("placeholders_removed"):
        lines.append(f"- {res['placeholders_removed']} line(s) the AI wrote with an unfilled template placeholder were removed.")
    if res.get("error"):
        lines.append(f"- The AI stopped early: {res['error']}")
    if res.get("open_items"):
        kinds = res.get("open_item_kinds") or ["decision"] * len(res["open_items"])
        dec = [it for it, k in zip(res["open_items"], kinds) if k == "decision"]
        inf = [it for it, k in zip(res["open_items"], kinds) if k != "decision"]
        if dec:
            lines += ["", "**Needs a decision from a person - nothing here was dropped, each item says what resolves it:**", ""]
            lines += [f"{n}. {it}" for n, it in enumerate(dec, 1)]
        if inf:
            lines += ["", "**For information - deliberately not generated, and why (act only if your BSP needs it):**", ""]
            lines += [f"- {it}" for it in inf]
    if res.get("facts_report"):
        lines += ["", "**What happened to each fact you gave:**", "", "| # | Fact | Result | Detail |", "|---|---|---|---|"]
        lines += [f"| {f['n']} | {f['fact']} | {f['status']} | {f['note']} |" for f in res["facts_report"]]
    if res["unsupported"]:
        lines += ["", "**Kept as comments (not active) - the AI added a specific that is not in the verified output, the evidence or your facts:**", "",
                  "| Line | What | Value |", "|---|---|---|"]
        lines += [f"| {u['line']} | {u['kind']} | `{u['token']}` |" for u in res["unsupported"]]
    if res["open_findings"]:
        lines += ["", "**Still failing the automatic checks:**"] + [f"- {f}" for f in res["open_findings"][:15]]
    if res["unverifiable_items"]:
        lines += ["", "**Cannot be verified from the workbook (needs your confirmation):**"] + [f"- {u}" for u in res["unverifiable_items"][:10]]
    if res["diff"].strip():
        lines += ["", "<details><summary>Diff: Python-only output -> hybrid final</summary>", "", "```diff", res["diff"].rstrip("\n"), "```", "", "</details>"]
    return lines
